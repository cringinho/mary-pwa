/**
 * Seeda o banco de dados SQLite com as 1.000 questões caso ainda não existam.
 */
export function seedMinigameQuestions(sqlite) {
  const countRow = sqlite.prepare('SELECT count(*) as count FROM minigame_questions WHERE is_custom = 0').get();
  const existingCount = countRow ? countRow.count : 0;

  if (existingCount >= 1000) {
    return;
  }

  const allQuestions = generateAll1000Questions();
  const now = new Date().toISOString();

  const insertStmt = sqlite.prepare(`
    INSERT INTO minigame_questions (question_type, category, question_text, option_a, option_b, is_custom, couple_id, created_by, created_at)
    VALUES (?, ?, ?, ?, ?, 0, NULL, NULL, ?)
  `);

  // Inserção em transação de alto desempenho
  const insertMany = sqlite.transaction((items) => {
    for (const q of items) {
      insertStmt.run(q.questionType, q.category, q.questionText, q.optionA, q.optionB, now);
    }
  });

  insertMany(allQuestions);
}
